from __future__ import annotations

import os
from dataclasses import dataclass
from typing import Any, Callable, Optional

from fastapi import APIRouter, Depends, Header, HTTPException, Query

from automation_hub.api.auth.deps import require_scope

# T1.6 / 决策 2026-08-23：hub personal 域降级为桌面权威源的只读镜像。
# 当镜像锁开启时，personal 域写入端点（POST/PUT/DELETE）仅接受携带
# `X-Siyi-Sync-Source: desktop` 头的请求（即桌面同步客户端），其余写入一律 403。
# V2-01（2026-08-24）：默认改为开启（桌面权威收敛落地）；需显式
# SIYI_HUB_PERSONAL_MIRROR_LOCK=0 才关闭（仅供迁移期回退）。
PERSONAL_MIRROR_SYNC_HEADER = "X-Siyi-Sync-Source"
PERSONAL_MIRROR_SYNC_VALUE = "desktop"


def personal_mirror_lock_enabled() -> bool:
    """镜像锁是否开启：默认开（桌面为 personal 域唯一真源），设置
    SIYI_HUB_PERSONAL_MIRROR_LOCK=0 显式关闭（仅迁移期回退用）。"""
    return os.environ.get("SIYI_HUB_PERSONAL_MIRROR_LOCK", "1").strip() != "0"


def require_desktop_sync_source(
    sync_source: str = Header(default="", alias=PERSONAL_MIRROR_SYNC_HEADER),
) -> None:
    """写入端点来源守卫：镜像锁开启时，仅允许桌面同步来源写入。"""
    if not personal_mirror_lock_enabled():
        return
    if sync_source.strip().lower() != PERSONAL_MIRROR_SYNC_VALUE:
        raise HTTPException(
            status_code=403,
            detail="personal domain is a read-only mirror of the desktop source of truth; "
                   "writes require desktop sync origin",
        )


@dataclass
class PersonalEntity:
    """Configuration for a personal-data CRUD router.

    Each entity (note, task, news item, translation, wordbook, word)
    maps to one router generated by create_personal_router().
    """

    # Routing
    prefix: str
    tag: str
    # Auth scopes
    scope_read: str
    scope_write: str
    # Response envelope key (e.g. "note", "task", "items")
    response_key: str
    # 404 detail message
    detail_not_found: str
    # DB functions (callable(user_id, ...) -> dict | list[dict] | None)
    db_list: Callable
    db_upsert: Callable
    db_delete: Callable
    # Optional GET-by-id (enables GET /{remote_id} endpoint)
    db_get: Optional[Callable] = None


def create_personal_router(entity: PersonalEntity) -> APIRouter:
    """Build a standard 5-endpoint CRUD router for a personal-data entity.

    Endpoints
    --------
    GET    /{remote_id}   — get single entity (only when entity.db_get is set)
    GET                  — list entities (since_updated_at, limit)
    POST                 — create / upsert by posted payload
    PUT   /{remote_id}   — update by remote_id
    DELETE /{remote_id}   — delete by remote_id
    """
    router = APIRouter(prefix=entity.prefix, tags=[entity.tag])
    rk = entity.response_key

    # ── GET /{remote_id} ──

    if entity.db_get is not None:

        @router.get("/{remote_id}")
        def get_by_remote_id(
            remote_id: str,
            token=Depends(require_scope(entity.scope_read)),
        ):
            obj = entity.db_get(token["user_id"], remote_id)
            if obj is None:
                raise HTTPException(status_code=404, detail=entity.detail_not_found)
            return {rk: obj}

    # ── GET (list) ──

    @router.get("")
    def list_entities(
        since_updated_at: str | None = Query(default=None),
        limit: int = Query(default=100, ge=1, le=200),
        token=Depends(require_scope(entity.scope_read)),
    ):
        items = entity.db_list(
            token["user_id"],
            since_updated_at=since_updated_at,
            limit=limit,
        )
        return {rk: items, "count": len(items), "next_cursor": None}

    # ── POST (create) ──

    @router.post("")
    def create_entity(
        payload: dict[str, Any],
        _sync=Depends(require_desktop_sync_source),
        token=Depends(require_scope(entity.scope_write)),
    ):
        obj = entity.db_upsert(token["user_id"], payload)
        return {rk: obj}

    # ── PUT /{remote_id} (update) ──

    @router.put("/{remote_id}")
    def update_entity(
        remote_id: str,
        payload: dict[str, Any],
        _sync=Depends(require_desktop_sync_source),
        token=Depends(require_scope(entity.scope_write)),
    ):
        obj = entity.db_upsert(token["user_id"], payload, remote_id=remote_id)
        return {rk: obj}

    # ── DELETE /{remote_id} ──

    @router.delete("/{remote_id}")
    def delete_entity(
        remote_id: str,
        _sync=Depends(require_desktop_sync_source),
        token=Depends(require_scope(entity.scope_write)),
    ):
        obj = entity.db_delete(token["user_id"], remote_id)
        if obj is None:
            raise HTTPException(status_code=404, detail=entity.detail_not_found)
        return {rk: obj}

    return router
