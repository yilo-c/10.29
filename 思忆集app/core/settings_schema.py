# re-export: 迁移逻辑（lazy import 避免 settings_schema shim → core.settings_migration 循环）
def __getattr__(name: str):
    if name in {"_to_bool", "_to_int", "_to_str", "_to_str_list", "_to_dict", "migrate_settings_repository"}:
        from core.settings_migration import (
            _to_bool, _to_int, _to_str, _to_str_list, _to_dict, migrate_settings_repository,
        )
        return locals()[name]
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
